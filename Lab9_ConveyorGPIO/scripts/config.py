# วินาทีที่ยอมรอคำตอบจาก Arduino หนึ่งบรรทัด
SERIAL_TIMEOUT = 2.0

# Uno จะรีเซ็ตตัวเองทุกครั้งที่มีคนเปิดพอร์ตอนุกรม (สาย DTR ดึงขา reset)
# ต้องรอให้บูตจบก่อนส่งคำสั่งแรก ไม่งั้นคำสั่งจะหายไปกับ bootloader
RESET_WAIT = 2.0

